#!/usr/bin/env node
/**
 * Snapshot the extension's tool descriptors into the standalone MCP bundle.
 *
 * The MCP host asks for tools before Chrome necessarily connects, so the
 * server cannot rely on LIST_TOOLS over the bridge for initial discovery.
 * Loading through Vite lets this build step import the TypeScript catalog and
 * its @ alias without moving the extension's handlers into the Node bundle.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createServer } from 'vite';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const output = join(root, 'mcpb', 'server', 'tool-catalog.mjs');

export async function buildMcpbToolCatalog() {
  const vite = await createServer({
    root,
    configFile: false,
    appType: 'custom',
    logLevel: 'error',
    server: { middlewareMode: true },
    resolve: { alias: { '@': join(root, 'src') } },
  });

  try {
    const { agentToolCatalog } = await vite.ssrLoadModule('/src/lib/agent-tools/catalog.ts');
    const descriptors = agentToolCatalog.map(({ name, description, inputSchema }) => ({
      name,
      description,
      inputSchema,
    }));
    const names = new Set(descriptors.map(({ name }) => name));
    if (names.size !== descriptors.length) {
      throw new Error('agent tool names must be unique');
    }

    writeFileSync(
      output,
      [
        '/**',
        ' * Generated by scripts/build-mcpb-tool-catalog.mjs.',
        ' * Do not edit by hand; run `npm run mcpb:catalog` after changing the agent catalog.',
        ' */',
        `export const STATIC_TOOL_CATALOG = Object.freeze(${JSON.stringify(descriptors, null, 2)});`,
        '',
      ].join('\n')
    );
  } finally {
    await vite.close();
  }

  return output;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const path = await buildMcpbToolCatalog();
  console.log(`Generated ${path}`);
}
